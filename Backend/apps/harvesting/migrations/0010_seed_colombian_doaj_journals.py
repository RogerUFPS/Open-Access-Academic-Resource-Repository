def _active_relation(model, *, user_id, defaults=None, **lookup):
    relation = model.objects.filter(**lookup).first()
    if relation is None:
        return model.objects.create(
            **lookup,
            created_by_id=user_id,
            **(defaults or {}),
        )

    updates = {
        "deleted_at": None,
        "deleted_by_id": None,
        "delete_explanation": None,
    }
    if defaults:
        updates.update(defaults)
    model.objects.filter(pk=relation.pk).update(**updates)
    for field, value in updates.items():
        setattr(relation, field, value)
    return relation


def seed_doaj_journals(apps, schema_editor):
    User = apps.get_model("account", "User")
    Country = apps.get_model("catalog", "Country")
    Editorial = apps.get_model("catalog", "Editorial")
    Language = apps.get_model("catalog", "Language")
    MaterialType = apps.get_model("catalog", "MaterialType")
    AcademicProgram = apps.get_model("catalog", "AcademicProgram")
    ProgramArea = apps.get_model("catalog", "SharedAcademicProgramKnowledgeArea")
    Platform = apps.get_model("platforms", "Platform")
    LinkCheckLog = apps.get_model("platforms", "LinkCheckLog")
    Journal = apps.get_model("journal", "Journal")
    License = apps.get_model("journal", "License")
    JournalLanguage = apps.get_model("journal", "SharedJournalLanguage")
    JournalCountry = apps.get_model("journal", "SharedJournalCountry")
    JournalArea = apps.get_model("journal", "SharedJournalKnowledgeArea")
    JournalMaterialType = apps.get_model("journal", "SharedJournalMaterialType")
    JournalProgram = apps.get_model("journal", "SharedJournalAcademicProgram")
    JournalPlatform = apps.get_model("journal", "SharedJournalPlatform")
    JournalLicense = apps.get_model("journal", "SharedJournalLicense")
    Harvest = apps.get_model("harvesting", "Harvest")
    HarvestJournal = apps.get_model("harvesting", "HarvestJournal")

    user = User.objects.filter(code=0).first()
    if user is None:
        raise RuntimeError(
            "No se puede cargar la cosecha DOAJ: falta el usuario sistema con code=0."
        )

    country = Country.objects.filter(abbreviation__iexact="CO").first()
    material_type = MaterialType.objects.filter(name__iexact="revista").first()
    if country is None or material_type is None:
        raise RuntimeError(
            "No se puede cargar la cosecha DOAJ: faltan Colombia o el tipo Revista."
        )

    platform = Platform.objects.filter(name__iexact="DOAJ").first()
    if platform is None:
        platform = Platform.objects.create(
            name="doaj",
            status="publicado",
            base_api_url=(
                "https://doaj.org/oai?"
                "verb=ListRecords&metadataPrefix=oai_dc"
            ),
            is_harvestable=True,
            start_period=HARVESTED_AT.date(),
            has_access_text=True,
            requires_registration=False,
            created_by_id=user.pk,
        )
    else:
        Platform.objects.filter(pk=platform.pk).update(
            status="publicado",
            base_api_url=(
                "https://doaj.org/oai?"
                "verb=ListRecords&metadataPrefix=oai_dc"
            ),
            is_harvestable=True,
            has_access_text=True,
            requires_registration=False,
            deleted_at=None,
            deleted_by_id=None,
            delete_explanation=None,
        )
        platform.refresh_from_db()

    harvest = Harvest.objects.create(
        platform_id=platform.pk,
        api_cursor="",
        api_marker=0,
        api_page="",
        worker_checkpoint=0,
        worker_elapsed_milliseconds=0,
        max_quantity=len(DOAJ_JOURNALS),
        state="completed",
        records_added=0,
        records_updated=0,
        records_failed=0,
        elapsed_seconds=0,
        started_at=HARVESTED_AT,
        finished_at=HARVESTED_AT,
        created_by_id=user.pk,
    )
    Harvest.objects.filter(pk=harvest.pk).update(created_at=HARVESTED_AT)

    added = 0
    updated = 0
    for row in DOAJ_JOURNALS:
        editorial = Editorial.objects.filter(name__iexact=row["editorial"]).first()
        if editorial is None:
            editorial = Editorial.objects.create(
                name=row["editorial"],
                created_by_id=user.pk,
            )
        elif editorial.deleted_at is not None:
            Editorial.objects.filter(pk=editorial.pk).update(
                deleted_at=None,
                deleted_by_id=None,
                delete_explanation=None,
            )

        journal = Journal.objects.filter(issn__iexact=row["issn"]).first()
        result = "updated"
        values = {
            "title": row["title"],
            "editorial_id": editorial.pk,
            "has_apc": row["has_apc"],
            "active": False,
            "publication_date": date(row["publication_year"], 1, 1),
            "validated_by_id": None,
            "validated_at": None,
            "fetched_at": HARVESTED_AT,
            "deleted_at": None,
            "deleted_by_id": None,
            "delete_explanation": None,
        }
        if journal is None:
            journal = Journal.objects.create(
                issn=row["issn"],
                created_by_id=user.pk,
                **values,
            )
            result = "added"
            added += 1
        else:
            values.update({
                "updated_by_id": user.pk,
                "updated_at": HARVESTED_AT,
            })
            Journal.objects.filter(pk=journal.pk).update(**values)
            journal.refresh_from_db()
            updated += 1

        for code in row["languages"]:
            language = Language.objects.filter(abbreviation__iexact=code).first()
            if language is None:
                raise RuntimeError(
                    f"No existe el idioma {code!r} requerido por {row['issn']}."
                )
            _active_relation(
                JournalLanguage,
                user_id=user.pk,
                journal_id=journal.pk,
                language_id=language.pk,
            )

        _active_relation(
            JournalCountry,
            user_id=user.pk,
            journal_id=journal.pk,
            country_id=country.pk,
        )
        _active_relation(
            JournalMaterialType,
            user_id=user.pk,
            journal_id=journal.pk,
            material_type_id=material_type.pk,
        )

        for program_name in row["programs"]:
            program = AcademicProgram.objects.filter(
                name__iexact=program_name
            ).first()
            if program is None:
                raise RuntimeError(
                    f"No existe el programa {program_name!r} requerido por {row['issn']}."
                )
            _active_relation(
                JournalProgram,
                user_id=user.pk,
                journal_id=journal.pk,
                academic_program_id=program.pk,
            )
            area_ids = ProgramArea.objects.filter(
                academic_program_id=program.pk,
                deleted_at__isnull=True,
            ).values_list("knowledge_area_id", flat=True)
            for area_id in area_ids:
                _active_relation(
                    JournalArea,
                    user_id=user.pk,
                    defaults={"is_manual": False, "is_derived": True},
                    journal_id=journal.pk,
                    knowledge_area_id=area_id,
                )

        license_obj = License.objects.filter(name__iexact=row["license"]).first()
        if license_obj is None:
            license_obj = License.objects.create(
                name=row["license"],
                created_by_id=user.pk,
            )
        elif license_obj.deleted_at is not None:
            License.objects.filter(pk=license_obj.pk).update(
                deleted_at=None,
                deleted_by_id=None,
                delete_explanation=None,
            )
        _active_relation(
            JournalLicense,
            user_id=user.pk,
            journal_id=journal.pk,
            license_id=license_obj.pk,
        )

        journal_platform = _active_relation(
            JournalPlatform,
            user_id=user.pk,
            defaults={
                "start_period": platform.start_period or HARVESTED_AT.date(),
                "finish_period": None,
                "has_full_text": True,
            },
            journal_id=journal.pk,
            platform_id=platform.pk,
        )
        link_log = LinkCheckLog.objects.create(
            platform_id=platform.pk,
            journal_platform_id=journal_platform.pk,
            url=row["official_url"],
            fail_count=0 if row["url_available"] else 1,
            http_status_code=row["http_status"],
            is_active=row["url_available"],
            last_check=HARVESTED_AT,
            created_by_id=user.pk,
        )
        LinkCheckLog.objects.filter(pk=link_log.pk).update(
            created_at=HARVESTED_AT
        )

        harvest_link = HarvestJournal.objects.create(
            harvest_id=harvest.pk,
            journal_id=journal.pk,
            result=result,
        )
        HarvestJournal.objects.filter(pk=harvest_link.pk).update(
            created_at=HARVESTED_AT
        )

    Harvest.objects.filter(pk=harvest.pk).update(
        records_added=added,
        records_updated=updated,
    )


